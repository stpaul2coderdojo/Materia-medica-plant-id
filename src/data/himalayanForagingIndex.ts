// Helper functions for quick lookup and category indexing
export function getEntriesByCategory(category: string): CulinaryReverseIndexEntry[] {
  if (category === "all") return HIMALAYAN_FORAGING_REVERSE_INDEX;
  return HIMALAYAN_FORAGING_REVERSE_INDEX.filter((e) => e.category === category);
}

export function searchForagingIndex(query: string): CulinaryReverseIndexEntry[] {
  const q = query.toLowerCase().trim();
  if (!q) return HIMALAYAN_FORAGING_REVERSE_INDEX;
  return HIMALAYAN_FORAGING_REVERSE_INDEX.filter(
    (e) =>
      e.scientificName.toLowerCase().includes(q) ||
      e.commonName.toLowerCase().includes(q) ||
      (e.vernacularName && e.vernacularName.toLowerCase().includes(q)) ||
      e.primaryEdiblePart.toLowerCase().includes(q) ||
      e.flavorProfile.toLowerCase().includes(q) ||
      e.himalayanRegion.toLowerCase().includes(q) ||
      e.recipePairing.toLowerCase().includes(q) ||
      e.categoryTitle.toLowerCase().includes(q)
  );
}
